"""
export.py — regenerates data.js from the SQLite database + config.json.

data.js sits next to dashboard.html and is loaded with a plain
    <script src="data.js"></script>
tag (never fetch()), so the dashboard works when opened straight off
disk via file:// with no server and no internet. The bot token in
config.json is deliberately NOT copied into data.js — only currency,
budgets and category list, which are safe to expose in a browser file.
"""

import json
from pathlib import Path

import db
from parser import CATEGORY_KEYWORDS

BASE_DIR = Path(__file__).parent
CONFIG_PATH = BASE_DIR / "config.json"
DATA_JS_PATH = BASE_DIR / "data.js"


def load_config() -> dict:
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def build_export_config(cfg: dict) -> dict:
    """Strip anything sensitive (the bot token) before it reaches the browser file."""
    return {
        "currency": cfg.get("currency", "₹"),
        "locale": cfg.get("locale", "en-IN"),
        "monthlyBudget": cfg.get("monthlyBudget", 0),
        "budgets": cfg.get("budgets", {}),
        "categories": list(CATEGORY_KEYWORDS.keys()) + ["income"],
    }


def run():
    db.init_db()
    cfg = load_config()
    export_cfg = build_export_config(cfg)
    rows = db.all_rows()

    # keep the fields the dashboard actually needs; drop chat_id (irrelevant
    # to the browser file, and mildly nice not to expose it either)
    slim_rows = [
        {
            "id": r["id"],
            "date": r["date"],
            "category": r["category"],
            "amount": r["amount"],
            "note": r["note"] or "",
            "type": r["type"],
        }
        for r in rows
    ]

    js = (
        "// Auto-generated by export.py — do not edit by hand.\n"
        f"window.EXPENSE_DATA = {json.dumps(slim_rows, ensure_ascii=False, indent=2)};\n"
        f"window.EXPENSE_CONFIG = {json.dumps(export_cfg, ensure_ascii=False, indent=2)};\n"
    )

    DATA_JS_PATH.write_text(js, encoding="utf-8")
    return len(slim_rows)


if __name__ == "__main__":
    n = run()
    print(f"wrote {DATA_JS_PATH} with {n} transactions")
